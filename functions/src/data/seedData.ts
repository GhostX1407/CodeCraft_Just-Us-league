/**
 * Seeds all synthetic demo data into Firestore collections.
 */
export async function seedAllDemoData(baseTime: number = Date.now()): Promise<{
  hospitalsCount: number;
  casesCount: number;
  reliabilityCount: number;
  auditCount: number;
  requestsCount: number;
  holdsCount: number;
}> {
  const db = getDb();
  let hospitalsCount = 0;
  let casesCount = 0;
  let reliabilityCount = 0;
  let auditCount = 0;
  let requestsCount = 0;
  let holdsCount = 0;

  const hospitals = generateDemoHospitals(baseTime);
  const cases = generateDemoCases(baseTime);
  const requests = generateDemoRequests(baseTime);
  const holds = generateDemoHolds(baseTime);
  const auditLogs = generateDemoAuditLogs(baseTime);

  // 1. Seed Hospitals & Reliability
  for (const hospital of hospitals) {
    await HospitalRepository.create(hospital);
    hospitalsCount++;

    const score = hospital.reliability_score;
    const acceptedCount = score !== null && score !== undefined ? 15 : 0;
    const honoredCount = score !== null && score !== undefined ? Math.round(score * acceptedCount) : 0;

    await db
      .collection('hospital_reliability')
      .doc(hospital.id)
      .set({
        hospital_id: hospital.id,
        hospital_name: hospital.name,
        accepted_commitments: acceptedCount,
        honored_commitments: honoredCount,
        reliability_score: score,
        updated_at: new Date(baseTime).toISOString(),
      });
    reliabilityCount++;
  }

  // 2. Seed Cases
  for (const caseItem of cases) {
    await CaseRepository.create(caseItem);
    casesCount++;
  }

  // 3. Seed Requests
  for (const request of requests) {
    await RequestRepository.create(request);
    requestsCount++;
  }

  // 4. Seed Holds
  for (const hold of holds) {
    await HoldRepository.create(hold);
    holdsCount++;
  }

  // 5. Seed Audit Logs
  for (const log of auditLogs) {
    await AuditRepository.append(log);
    auditCount++;
  }

  return {
    hospitalsCount,
    casesCount,
    reliabilityCount,
    auditCount,
    requestsCount,
    holdsCount,
  };
}
